function base64Bytes(encoded: string): Uint8Array {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  const bytes: number[] = [];
  let value = 0;
  let bits = 0;
  for (const char of encoded) {
    if (char === '=') break;
    const digit = alphabet.indexOf(char);
    if (digit < 0) throw new Error('Invalid sword pixel');
    value = (value << 6) | digit;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      bytes.push((value >>> bits) & 255);
    }
  }
  return Uint8Array.from(bytes);
}

export function officialSwordSprite(
  kind: ItemKind,
  style: 'ground' | 'icon',
): PixelImage | undefined {
  const source = SWORDS[kind];
  if (!source) return undefined;
  const indices = base64Bytes(source.pixels);
  const image = new PixelImage(source.width, source.height);
  for (let i = 0; i < indices.length; i++) {
    const color = source.palette[indices[i] ?? -1] ?? '00000000';
    const n = Number.parseInt(color, 16);
    image.data[i * 4] = n >>> 24;
    image.data[i * 4 + 1] = (n >>> 16) & 255;
    image.data[i * 4 + 2] = (n >>> 8) & 255;
    image.data[i * 4 + 3] = n & 255;
  }
  return style === 'icon' ? doubled(image) : image;
}
