/** ¿Comercia (o guarda cosas)? Con los demás solo se charla. */
export function isMerchant(role: NpcRole): boolean {
  return (
    role === 'banker' ||
    role === 'stablemaster' ||
    VENDORS[role].sells.length > 0 ||
    VENDORS[role].buys.length > 0
  );
}

