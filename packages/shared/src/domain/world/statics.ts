export function isStaticKind(value: unknown): value is StaticKind {
  return typeof value === 'string' && (STATIC_KINDS as readonly string[]).includes(value);
}

export interface StaticPlacement {
  readonly kind: StaticKind;
  readonly x: number;
  readonly y: number;
}
