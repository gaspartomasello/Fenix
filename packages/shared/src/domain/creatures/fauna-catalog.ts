/** Cómo se porta con la gente: huye, se defiende si la atacan o ataca apenas ve a alguien. */
type Temper = 'timid' | 'passive' | 'aggressive';

interface Beast {
  readonly name: string;
  readonly article: 'un' | 'una';
  readonly hits: number;
  readonly dexterity: number;
  readonly armor?: number;
  readonly skill: number;
  readonly damage: readonly [number, number];
  readonly attack: string;
  readonly swingMs?: number;
  readonly moveMs: number;
  readonly temper: Temper;
  /** A qué distancia ataca (las fieras). */
  readonly aggro?: number;
  readonly loot: readonly LootEntry[];
  readonly poison?: { readonly chance: number; readonly level: number };
  readonly humanoid?: boolean;
  readonly skillName?: 'wrestling' | 'fencing';
}

