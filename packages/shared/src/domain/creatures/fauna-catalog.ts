/** Las definiciones de la fauna, en el formato de todas las criaturas. */
export function faunaDefinitions(): Record<FaunaKind, CreatureDefinition> {
  const entries = FAUNA_KINDS.map((kind): [FaunaKind, CreatureDefinition] => {
    const b = BEASTS[kind];
    const abilities = {
      ...(b.poison ? { poison: b.poison } : {}),
      // Las presas escapan apenas las tocan.
      ...(b.temper === 'timid' ? { fleeAt: 1 } : {}),
    };
    return [
      kind,
      {
        kind,
        name: b.name,
        article: b.article,
        maxHits: b.hits,
        strength: Math.round(b.hits * 0.8 + 10),
        dexterity: b.dexterity,
        armor: b.armor ?? 2,
        skill: b.skill,
        weapon: {
          name: b.attack,
          minDamage: b.damage[0],
          maxDamage: b.damage[1],
          swingMs: b.swingMs ?? 2000,
          skill: b.skillName ?? 'wrestling',
        },
        moveMs: b.moveMs,
        // Las mansas no buscan pelea: solo devuelven los golpes (o huyen).
        aggroRange: b.temper === 'aggressive' ? (b.aggro ?? 5) : 0,
        loot: b.loot,
        humanoid: b.humanoid ?? false,
        summoned: false,
        ...(Object.keys(abilities).length > 0 ? { abilities } : {}),
      },
    ];
  });
  return Object.fromEntries(entries) as Record<FaunaKind, CreatureDefinition>;
}

export function isFaunaKind(value: unknown): value is FaunaKind {
  return typeof value === 'string' && (FAUNA_KINDS as readonly string[]).includes(value);
}
